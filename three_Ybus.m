function Ybus = three_Ybus(data)

%% ============================================================
% MODULE 3
% BUILD YBUS MATRIX
%
% IEEE-39 BUS SYSTEM
% ============================================================


%% ============================================================
% 1. NUMBER OF BUSES
% ============================================================

nBus = length(data.bus);


%% ============================================================
% 2. CREATE INITIAL YBUS MATRIX
% ============================================================

Ybus = zeros(nBus,nBus);


%% ============================================================
% 3. PROCESS EACH LINE
% ============================================================

for k = 1:length(data.fromBus)


    %% --------------------------------------------------------
    % Get From and To bus
    % --------------------------------------------------------

    i = data.fromBus(k);
    j = data.toBus(k);


    %% --------------------------------------------------------
    % Check whether line is in service
    % --------------------------------------------------------

    if data.lineStatus(k) == 0

        continue

    end


    %% --------------------------------------------------------
    % Get line data
    % --------------------------------------------------------

    R = data.Rline(k);

    X = data.Xline(k);

    B = data.Bline(k);


    %% --------------------------------------------------------
    % Get transformer tap
    % --------------------------------------------------------

    tapMag = data.tap(k);

    tapAngle = data.tapAngle(k);


    % If tap is zero, use unity tap

    if tapMag == 0

        tapMag = 1;

    end


    % If tap angle is NaN, use zero

    if isnan(tapAngle)

        tapAngle = 0;

    end


    %% --------------------------------------------------------
    % Convert tap angle from degrees to radians
    % --------------------------------------------------------

    tapAngle_rad = tapAngle*pi/180;


    %% --------------------------------------------------------
    % Create complex transformer tap
    % --------------------------------------------------------

    tap = tapMag*exp(1i*tapAngle_rad);


    %% --------------------------------------------------------
    % Series impedance
    % --------------------------------------------------------

    Z = R + 1i*X;


    % Check for zero impedance

    if Z == 0

        error('Zero series impedance found.');

    end


    %% --------------------------------------------------------
    % Series admittance
    % --------------------------------------------------------

    y = 1/Z;


    %% --------------------------------------------------------
    % Half-line charging admittance
    % --------------------------------------------------------

    ysh = 1i*B/2;


    %% --------------------------------------------------------
    % Add diagonal element at From bus
    % --------------------------------------------------------

    Ybus(i,i) = Ybus(i,i) + ...
        (y + ysh)/(abs(tap)^2);


    %% --------------------------------------------------------
    % Add diagonal element at To bus
    % --------------------------------------------------------

    Ybus(j,j) = Ybus(j,j) + ...
        y + ysh;


    %% --------------------------------------------------------
    % Add off-diagonal element
    % --------------------------------------------------------

    Ybus(i,j) = Ybus(i,j) - ...
        y/conj(tap);


    Ybus(j,i) = Ybus(j,i) - ...
        y/tap;


end


%% ============================================================
% 4. DISPLAY YBUS
% ============================================================

fprintf('\n');
fprintf('============================================\n');
fprintf('             MODULE 3: YBUS\n');
fprintf('============================================\n');

fprintf('Number of buses = %d\n',nBus);

fprintf('Ybus matrix created successfully.\n');

fprintf('============================================\n');


end
